-- 低レート帯の取り残し対策: キューで「何回のスキャンに取り残されたか」を数える。
--
-- 最下位付近の人はウィンドウ（07 §3-1）に入る相手が少なく、「あと 1〜2 人足りない」で
-- 残り続ける。走査方向のランダム化（07 §4-3）で緩和したが、そもそも近い帯に
-- 人がいなければ組めない。そこで **表示レート 1486 以下の人に限り**、スキャンに
-- 取り残されるたびに **マッチング範囲の判定にだけ使うレートを +14** する
-- （`matchmaker::boost`）。実レート（player_current_ratings）には触らないし、
-- formation に凍結する mu_at_match も実レートのまま。
--
-- 数えるのは「マッチメイカが実際に走り、その人を見て、組まなかった」回数。
-- 止まっている間（手動停止・稼働時間外）は数えない。行はキューを抜ける
-- （成立・離脱）と消えるので、カウンタもそこで消える。設定の更新では動かさない。
--
-- 実レートが 1486 を超えている人のカウンタも同じように増えるが、判定側で使わない
-- （閾値を 1 か所に置くため、列には条件を持たせない）。

alter table queue_entries
    add column unmatched_scans integer not null default 0
        check (unmatched_scans >= 0);

comment on column queue_entries.unmatched_scans is
    'マッチメイカが走って、この行を見て、組まなかった回数。止まっている間は増えない。1486 以下の人はこの回数 x 14 をマッチング範囲の判定にだけ足す（matchmaker::boost）。実レートには影響しない';
